-- RUN AS ACCOUNTADMIN once, in a SQL file in the StayWise Snowsight workspace.
-- The dedicated names make the project easy to inspect and remove afterwards.

USE ROLE ACCOUNTADMIN;

-- Builder creates objects; app can only read approved marts and call fixed tools.
CREATE ROLE IF NOT EXISTS STAYWISE_BUILDER;
CREATE ROLE IF NOT EXISTS STAYWISE_APP;
GRANT ROLE STAYWISE_BUILDER TO ROLE SYSADMIN;
GRANT ROLE STAYWISE_APP TO ROLE STAYWISE_BUILDER;

-- Assign both roles to the currently signed-in user, without hardcoding a name.
SET deployment_user = CURRENT_USER();
GRANT ROLE STAYWISE_BUILDER TO USER IDENTIFIER($deployment_user);
GRANT ROLE STAYWISE_APP TO USER IDENTIFIER($deployment_user);

-- An X-Small warehouse with 60-second auto-suspend fits the supplied dataset.
CREATE WAREHOUSE IF NOT EXISTS STAYWISE_WH
    WAREHOUSE_SIZE = XSMALL
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

-- Bound individual SQL statements; this also limits a bad analytical query.
ALTER WAREHOUSE STAYWISE_WH
    SET STATEMENT_TIMEOUT_IN_SECONDS = 120;
GRANT USAGE, OPERATE ON WAREHOUSE STAYWISE_WH TO ROLE STAYWISE_BUILDER;
GRANT USAGE ON WAREHOUSE STAYWISE_WH TO ROLE STAYWISE_APP;
CREATE DATABASE IF NOT EXISTS STAYWISE_DB;

-- Grant ownership only for this dedicated project database.
GRANT OWNERSHIP ON DATABASE STAYWISE_DB
    TO ROLE STAYWISE_BUILDER
    COPY CURRENT GRANTS;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE STAYWISE_BUILDER;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE STAYWISE_APP;

-- RAW = landing; ANALYTICS = dbt; KNOWLEDGE = RAG; AI = tools; APP = UI/logs.
USE ROLE STAYWISE_BUILDER;
CREATE SCHEMA IF NOT EXISTS STAYWISE_DB.RAW;
CREATE SCHEMA IF NOT EXISTS STAYWISE_DB.ANALYTICS;
CREATE SCHEMA IF NOT EXISTS STAYWISE_DB.KNOWLEDGE;
CREATE SCHEMA IF NOT EXISTS STAYWISE_DB.AI;
CREATE SCHEMA IF NOT EXISTS STAYWISE_DB.APP;

-- Upload source assets through Ingestion > Add Data > Load files into a Stage.
-- Each stage separates one deployment concern.
-- SSE stages allow document functions to read PDFs; files are uploaded separately.
CREATE STAGE IF NOT EXISTS STAYWISE_DB.RAW.DATA_STAGE;
CREATE STAGE IF NOT EXISTS STAYWISE_DB.RAW.CODE_STAGE;
CREATE STAGE IF NOT EXISTS STAYWISE_DB.RAW.DBT_STAGE;
CREATE STAGE IF NOT EXISTS STAYWISE_DB.KNOWLEDGE.DOC_STAGE
    ENCRYPTION = (TYPE = 'SNOWFLAKE_SSE')
    DIRECTORY = (ENABLE = TRUE);
CREATE STAGE IF NOT EXISTS STAYWISE_DB.APP.APP_STAGE;
