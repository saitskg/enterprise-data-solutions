-- The application owns its Streamlit object but has no write access to reservations.

USE ROLE STAYWISE_BUILDER;

-- Parent USAGE permits name resolution; it does not itself expose table rows.
GRANT USAGE ON DATABASE STAYWISE_DB TO ROLE STAYWISE_APP;
GRANT USAGE ON SCHEMA STAYWISE_DB.ANALYTICS TO ROLE STAYWISE_APP;
GRANT USAGE ON SCHEMA STAYWISE_DB.KNOWLEDGE TO ROLE STAYWISE_APP;
GRANT USAGE ON SCHEMA STAYWISE_DB.AI TO ROLE STAYWISE_APP;
GRANT USAGE ON SCHEMA STAYWISE_DB.APP TO ROLE STAYWISE_APP;

-- Grant only the three curated tables actually read by the UI and Analyst adapter.
GRANT SELECT ON TABLE STAYWISE_DB.ANALYTICS.MART_BOOKING_CONTEXT
    TO ROLE STAYWISE_APP;
GRANT SELECT ON TABLE STAYWISE_DB.ANALYTICS.DIM_LISTING
    TO ROLE STAYWISE_APP;
GRANT SELECT ON TABLE STAYWISE_DB.ANALYTICS.MART_LISTING_PERFORMANCE
    TO ROLE STAYWISE_APP;

-- Service/procedure grants are separate from table privileges.
GRANT SELECT ON SEMANTIC VIEW STAYWISE_DB.AI.STAY_ANALYTICS
    TO ROLE STAYWISE_APP;
GRANT USAGE ON CORTEX SEARCH SERVICE STAYWISE_DB.KNOWLEDGE.STAY_SEARCH
    TO ROLE STAYWISE_APP;
GRANT USAGE ON PROCEDURE STAYWISE_DB.AI.FIND_AVAILABLE_STAYS(
    VARCHAR,
    VARCHAR,
    VARCHAR,
    NUMBER,
    VARCHAR,
    FLOAT
) TO ROLE STAYWISE_APP;
GRANT USAGE ON PROCEDURE STAYWISE_DB.AI.QUOTE_STAY_OPTION(
    VARCHAR,
    VARCHAR,
    VARCHAR,
    NUMBER,
    VARCHAR,
    VARCHAR,
    VARCHAR
) TO ROLE STAYWISE_APP;

-- Append-only application audit: the app can save investigations, but cannot
-- update bookings or read another representative's persisted request log.
CREATE TABLE IF NOT EXISTS STAYWISE_DB.APP.REQUEST_LOG (
    request_id VARCHAR,
    question VARCHAR,
    result VARIANT,
    created_at TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);

GRANT INSERT ON TABLE STAYWISE_DB.APP.REQUEST_LOG TO ROLE STAYWISE_APP;

-- The app owner can copy its staged sources when creating a Streamlit object.
GRANT READ ON STAGE STAYWISE_DB.APP.APP_STAGE TO ROLE STAYWISE_APP;
GRANT CREATE STREAMLIT ON SCHEMA STAYWISE_DB.APP TO ROLE STAYWISE_APP;
