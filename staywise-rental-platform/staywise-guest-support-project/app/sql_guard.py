"""A deliberately narrow SELECT validator in addition to Snowflake role privileges.

Analyst is instructed to use ordinary table SQL over MART_BOOKING_CONTEXT.
Unsupported semantic/table-function syntax is rejected instead of guessed at.
"""
import sqlglot
from sqlglot import exp
from sqlglot.optimizer.scope import traverse_scope

ALLOWED_TABLES = {"STAYWISE_DB.ANALYTICS.MART_BOOKING_CONTEXT"}
# Allow only familiar analytical functions; no arbitrary UDF/external function calls.
ALLOWED_FUNCTIONS = {
    "COUNT", "SUM", "AVG", "MIN", "MAX", "COALESCE", "IF", "IFF", "NULLIF",
    "CAST", "TRY_CAST", "DATE_TRUNC", "TIMESTAMP_TRUNC", "DATE_ADD", "DATEADD",
    "DATE_DIFF", "DATEDIFF", "TO_DATE", "DATE", "CURRENT_DATE", "CURRENT_TIMESTAMP",
    "EXTRACT", "YEAR", "MONTH", "DAY", "ROUND", "ABS", "LOWER", "UPPER", "TRIM",
    "TS_OR_DS_TO_DATE", "COUNT_IF",
    "CONCAT", "ROW_NUMBER", "RANK", "DENSE_RANK", "LENGTH", "CASE",
}


def validate_sql(sql):
    """Validate Analyst SQL structurally and cap its result to 100 rows.

    Args:
        sql (str): Untrusted SQL statement generated by Cortex Analyst.

    Returns:
        str: Snowflake SELECT wrapping the validated query with an outer LIMIT 100.

    Raises:
        sqlglot.errors.ParseError: The input cannot be parsed as Snowflake SQL.
        ValueError: Multiple statements, non-read operations, unapproved sources,
        table functions, qualified functions, or non-allowlisted functions occur.

    Notes:
        Resolves CTE scopes to check the underlying physical tables. Validation
        performs no database I/O and complements the application's role grants;
        it does not replace Snowflake's permission checks or statement timeouts.
    """
    # Parse syntax rather than looking for keywords hidden in comments or strings.
    statements = sqlglot.parse(sql, read="snowflake")
    if len(statements) != 1 or not isinstance(statements[0], (exp.Select, exp.Union)):
        raise ValueError("Only one SELECT query is allowed")
    tree = statements[0]
    if any(tree.find_all(exp.Into, exp.Command, exp.Insert, exp.Update, exp.Delete, exp.Create, exp.Drop)):
        raise ValueError("SQL contains a disallowed operation")
    table_count = 0
    # Scope resolution prevents a CTE alias from concealing a forbidden real table.
    for scope in traverse_scope(tree):
        for source in scope.sources.values():
            if isinstance(source, exp.Table):
                if not isinstance(source.this, exp.Identifier):
                    raise ValueError("Table functions are outside this application's SQL contract")
                name = ".".join(part.name.upper() for part in source.parts)
                if name not in ALLOWED_TABLES:
                    raise ValueError(f"Query must use approved fully qualified table names: {name}")
                table_count += 1
    if not table_count:
        raise ValueError("Query must read an approved data mart")
    # Table access alone is insufficient: a SELECT could call a side-effecting UDF.
    for function in tree.find_all(exp.Func):
        if isinstance(function.parent, exp.Dot):
            raise ValueError("Qualified function calls are not enabled")
        name = function.name.upper() if isinstance(function, exp.Anonymous) else function.sql_name().upper()
        if name not in ALLOWED_FUNCTIONS:
            raise ValueError(f"Function {name} is not enabled in this query tool")
    # Apply a limit outside the query, preserving its aggregate/ORDER BY semantics.
    return f"SELECT * FROM ({tree.sql(dialect='snowflake')}) AS limited_result LIMIT 100"
